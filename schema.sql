CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT UNIQUE NOT NULL,
    username TEXT,
    name TEXT
);

CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS owners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    text TEXT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'rejected')),
    photo TEXT,
    author_username TEXT,
    author_name TEXT
);

ALTER TABLE posts ADD COLUMN IF NOT EXISTS author_username TEXT;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS author_name TEXT;

-- Older posts only have the sender ID; fill the available current profile data.
-- New posts always save author_name, so their snapshots are never overwritten.
UPDATE posts AS p
SET author_username = u.username, author_name = u.name
FROM users AS u
WHERE u.telegram_id = p.user_id AND p.author_name IS NULL;
